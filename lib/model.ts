// Token Radar, model radar-2: peer multiples from the snapshot's own live-token market.
//
// The board ranks every protocol on the snapshot's watchlist plus every other
// rankable pre-token protocol below the watchlist floor. A protocol is pre-token
// when its record carries no token (no market cap, no CoinGecko id, no symbol),
// and rankable when it is not a wrapped, staked or bridged product of a token
// that already trades (the house watchlist rule, applied here to the early rows
// too: excluded categories, versioned names, wrapped/staked/staking words,
// exchange-prefixed names). Twenty pre-token protocols sit above the floor yet
// are not on the watchlist; the snapshot carries no parentProtocol field, so the
// house rule that left them out cannot be re-derived here and they are not
// ranked — they are listed separately in the dashboard as set aside.
//
// Implied value follows only from the snapshot's own figures:
//
//   peer     = median(mcap_usd / tvl_usd) over live-token protocols in the same
//              category (at least 3 peers with a market cap and TVL, else the
//              global median over all such protocols), winsorised to [0.05, 3.0]
//   growth   = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturityMult = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   chainMult    = 1 + 0.03 x min(chains - 1, 3)
//   implied  = max(1, round(tvl_usd x peer x growthMult x maturityMult x chainMult))
//
// The peer multiple is the model's one claim: a token, when it launches, is
// priced by the market the way the market already prices the tokens of
// protocols like it. No protocol name is ever special-cased: the same function
// scores every row, and every row carries the peer multiple and peer count it
// was scored with, so the number can be checked.

